import { NextRequest, NextResponse } from "next/server";
import { getCampaign } from "@/services/campaign.service";
import {
  buildCampaignImpactReportPdf,
  type CampaignImpactReportInput,
} from "@/services/campaign-impact-report.service";
import {
  deriveSpeciesBreakdown,
  getBackerDemographicsForReport,
  getCampaignImpactReport,
} from "@/services/automated-campaign-impact-report.service";

export const runtime = "nodejs";

/**
 * GET /api/reports/campaign/[id]
 *
 * Generate and download a campaign impact report PDF for the given campaign.
 * The report includes tree count, species breakdown, CO2 sequestration,
 * backer demographics, sponsor names, and stated project impact.
 *
 * Optional query params:
 *   - speciesBreakdown: JSON-encoded SpeciesBreakdownEntry[] for per-species
 *     data. When omitted, the breakdown is derived from the campaign record.
 *   - demographics: JSON-encoded BackerDemographicEntry[] for regional demographics.
 *   - inline: "true" or "1" to view inline in browser instead of attachment download.
 */
export async function GET(
  request: NextRequest,
  { params }: { params: Promise<{ id: string }> },
) {
  const { id } = await params;
  const campaign = await getCampaign(id);
  if (!campaign) {
    return NextResponse.json({ error: "Campaign not found" }, { status: 404 });
  }

  let speciesBreakdown: CampaignImpactReportInput["speciesBreakdown"] | undefined;
  const rawBreakdown = request.nextUrl.searchParams.get("speciesBreakdown");
  if (rawBreakdown) {
    try {
      const parsed = JSON.parse(rawBreakdown);
      if (Array.isArray(parsed)) {
        speciesBreakdown = parsed;
      }
    } catch {
      return NextResponse.json(
        { error: "speciesBreakdown must be a valid JSON array" },
        { status: 400 },
      );
    }
  } else {
    speciesBreakdown = deriveSpeciesBreakdown(campaign);
  }

  let demographics = await getBackerDemographicsForReport(campaign);
  const rawDemographics = request.nextUrl.searchParams.get("demographics");
  if (rawDemographics) {
    try {
      const parsed = JSON.parse(rawDemographics);
      if (Array.isArray(parsed)) {
        demographics = parsed;
      }
    } catch {
      return NextResponse.json(
        { error: "demographics must be a valid JSON array" },
        { status: 400 },
      );
    }
  }

  const isInline =
    request.nextUrl.searchParams.get("inline") === "true" ||
    request.nextUrl.searchParams.get("inline") === "1";

  const host = request.headers.get("host") || "localhost:3000";
  const protocol = host.startsWith("localhost") ? "http" : "https";
  const publicShareUrl = `${protocol}://${host}/campaigns/${campaign.id}/impact-report`;

  try {
    // If a cached report is available, we can use its pre-generated bytes if no custom query params
    let pdfBytes: Uint8Array | undefined;
    if (!rawBreakdown && !rawDemographics) {
      const existingReport = await getCampaignImpactReport(id);
      if (existingReport?.pdfBytes) {
        pdfBytes = existingReport.pdfBytes;
      }
    }

    if (!pdfBytes) {
      pdfBytes = await buildCampaignImpactReportPdf({
        campaign,
        speciesBreakdown,
        demographics,
        statedProjectImpact: campaign.description,
        publicShareUrl,
      });
    }

    const slug     = campaign.name.toLowerCase().replace(/[^a-z0-9]+/g, "-").slice(0, 40);
    const date     = new Date().toISOString().slice(0, 10);
    const filename = `fundable-impact-${slug}-${date}.pdf`;
    const dispositionType = isInline ? "inline" : "attachment";

    return new NextResponse(pdfBytes as unknown as BodyInit, {
      status: 200,
      headers: {
        "Content-Type":        "application/pdf",
        "Content-Disposition": `${dispositionType}; filename="${filename}"`,
        "Content-Length":      pdfBytes.byteLength.toString(),
        "Cache-Control":       "private, no-store",
      },
    });
  } catch (err) {
    console.error("[api/reports/campaign] PDF generation failed", err);
    return NextResponse.json(
      { error: "Unable to generate impact report" },
      { status: 500 },
    );
  }
}
